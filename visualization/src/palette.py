"""Общая палитра тем: карта и алювиальная рисуют кластеры одними цветами.

Цвет назначается по id глобального кластера в фиксированном порядке (не по
рангу и не по порядку отображения): родственные темы в разных эпохах — одного
цвета (ТЗ 5.6). Карта получает палитру через label_color_map, Sankey — через
node.color; так цвета согласованы между вкладками по построению.

Палитра собрана перебором: 48 оттенков по золотому углу × 2 уровня светлоты
(OKLCH L ≈ 0.55/0.63), жадный отбор 24 цветов с максимальным минимальным
расстоянием между соседями (OKLab ΔE, нормальное зрение и дейтеранопия).
Проверена валидатором dataviz-скилла (тёмная поверхность #1a1a19):
полоса светлоты 0.48–0.67, хрома ≥ 0.1, CVD ΔE ≥ 8, контраст ≥ 3:1 — все PASS.
"""
from __future__ import annotations

# 24 цвета хватает на KMeans-фолбэк (24 кластера) и на обычный HDBSCAN
# (цель ТЗ: 10–30); если кластеров больше — цвета повторяются по модулю.
COLORS = [
    "#896e0d", "#8919ff", "#fc191c", "#195efb", "#f53118", "#7045ff",
    "#e05616", "#5c57ff", "#d06814", "#4566ff", "#c57113", "#9418f3",
    "#fb192e", "#8845ff", "#b57c12", "#7157ff", "#9d890f", "#1767e7",
    "#a58410", "#a116df", "#908e0e", "#8b68ff", "#88910e", "#a957ff",
]

# Серый для «Прочее» (шум) — совпадает с noise_label на карте.
NOISE = "#8a8a8a"


def color_for(i: int) -> str:
    """HEX-цвет кластера i: фиксирован, стабилен между прогонами."""
    return COLORS[i % len(COLORS)]


def rgba(color: str, alpha: float) -> str:
    """HEX → rgba() (связи Sankey с прозрачностью, ТЗ 5.6)."""
    r, g, b = int(color[1:3], 16), int(color[3:5], 16), int(color[5:7], 16)
    return f"rgba({r},{g},{b},{alpha})"
